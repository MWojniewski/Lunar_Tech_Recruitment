#!/usr/bin/env python3
"""Plot lunar lander telemetry exported by the C simulation.

The script deliberately uses Python's CSV module instead of pandas so that the
visualization has only one runtime dependency: matplotlib.
"""

from __future__ import annotations

import argparse
import csv
import math
import os
import sys
from dataclasses import dataclass
from pathlib import Path

try:
    import matplotlib

    # WSL without WSLg has no display server. Select a safe renderer before
    # importing pyplot so normal file output remains available there.
    HAS_DISPLAY = bool(os.environ.get("DISPLAY") or os.environ.get("WAYLAND_DISPLAY"))
    if not HAS_DISPLAY:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    matplotlib = None
    plt = None


REQUIRED_COLUMNS = {"time", "height", "velocity", "engine_state"}
OPTIONAL_2D_COLUMNS = {"x", "vx", "rcs_state"}
DEFAULT_SAFE_VELOCITY = 1.0


@dataclass(frozen=True)
class Telemetry:
    """Numerical telemetry columns used by the plots."""

    time: list[float]
    height: list[float]
    velocity: list[float]
    engine_state: list[int]
    x: list[float] | None = None
    vx: list[float] | None = None

    @property
    def is_2d(self) -> bool:
        return self.x is not None and self.vx is not None


def parse_args() -> argparse.Namespace:
    """Parse command-line options for repeatable, script-friendly usage."""
    parser = argparse.ArgumentParser(
        description="Plot height, velocity, engine state, and optional 2D telemetry."
    )
    parser.add_argument(
        "input",
        type=Path,
        help="Telemetry CSV generated by lunar_lander.",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        help="PNG path (default: next to input CSV with a .png suffix).",
    )
    parser.add_argument(
        "--safe-velocity",
        type=float,
        default=DEFAULT_SAFE_VELOCITY,
        metavar="MPS",
        help=f"Safe touchdown speed threshold (default: {DEFAULT_SAFE_VELOCITY:g} m/s).",
    )
    parser.add_argument(
        "--show",
        action="store_true",
        help="Open the plot window after saving the image.",
    )
    return parser.parse_args()


def _parse_float(value: str | None, column: str, row_number: int) -> float:
    try:
        number = float(value) if value is not None else math.nan
    except (TypeError, ValueError) as error:
        raise ValueError(
            f"row {row_number}: column '{column}' must contain a number"
        ) from error
    if not math.isfinite(number):
        raise ValueError(f"row {row_number}: column '{column}' must be finite")
    return number


def _parse_int(value: str, column: str, row_number: int) -> int:
    number = _parse_float(value, column, row_number)
    if number not in (0.0, 1.0):
        raise ValueError(f"row {row_number}: column '{column}' must be 0 or 1")
    return int(number)


def load_telemetry(path: Path) -> Telemetry:
    """Load and validate telemetry without silently discarding malformed rows."""
    try:
        with path.open(newline="", encoding="utf-8") as csv_file:
            reader = csv.DictReader(csv_file)
            columns = set(reader.fieldnames or [])
            missing = REQUIRED_COLUMNS - columns
            if missing:
                missing_columns = ", ".join(sorted(missing))
                raise ValueError(f"missing required column(s): {missing_columns}")

            present_2d_columns = OPTIONAL_2D_COLUMNS.intersection(columns)
            if present_2d_columns and present_2d_columns != OPTIONAL_2D_COLUMNS:
                missing_2d_columns = ", ".join(
                    sorted(OPTIONAL_2D_COLUMNS - present_2d_columns)
                )
                raise ValueError(
                    "incomplete 2D telemetry; missing column(s): "
                    f"{missing_2d_columns}"
                )
            has_2d_columns = present_2d_columns == OPTIONAL_2D_COLUMNS
            time: list[float] = []
            height: list[float] = []
            velocity: list[float] = []
            engine_state: list[int] = []
            x: list[float] | None = [] if has_2d_columns else None
            vx: list[float] | None = [] if has_2d_columns else None

            for row_number, row in enumerate(reader, start=2):
                if not any(value and value.strip() for value in row.values()):
                    continue
                time.append(_parse_float(row["time"], "time", row_number))
                height.append(_parse_float(row["height"], "height", row_number))
                velocity.append(_parse_float(row["velocity"], "velocity", row_number))
                engine_state.append(
                    _parse_int(row["engine_state"], "engine_state", row_number)
                )
                if has_2d_columns and x is not None and vx is not None:
                    x.append(_parse_float(row["x"], "x", row_number))
                    vx.append(_parse_float(row["vx"], "vx", row_number))
    except FileNotFoundError as error:
        raise ValueError(f"input file does not exist: {path}") from error
    except OSError as error:
        raise ValueError(f"cannot read input file '{path}': {error}") from error

    if not time:
        raise ValueError("input CSV contains no telemetry rows")
    if any(later <= earlier for earlier, later in zip(time, time[1:])):
        raise ValueError("time values must be strictly increasing")
    return Telemetry(time, height, velocity, engine_state, x, vx)


def _plot_engine_state(axis, telemetry: Telemetry) -> None:
    """Render the discrete engine signal as a step plot."""
    axis.step(telemetry.time, telemetry.engine_state, where="post", color="#d95f02")
    axis.set_yticks((0, 1), labels=("OFF", "ON"))
    axis.set_ylim(-0.15, 1.15)
    axis.set_ylabel("Engine")
    axis.grid(axis="x", alpha=0.25)


def _touchdown_index(telemetry: Telemetry) -> int:
    """Return the first sample at or below ground, or the final sample."""
    for index, height in enumerate(telemetry.height):
        if height <= 0.0:
            return index
    return len(telemetry.time) - 1


def create_figure(telemetry: Telemetry, safe_velocity: float):
    """Create a figure while keeping plotting separate from file I/O."""
    row_count = 2 if telemetry.is_2d else 1
    figure, axes = plt.subplots(
        2 + row_count,
        1,
        figsize=(11, 10 if telemetry.is_2d else 8),
        sharex=True,
        constrained_layout=True,
    )
    axes = list(axes)
    touchdown = _touchdown_index(telemetry)
    touchdown_time = telemetry.time[touchdown]
    touchdown_velocity = telemetry.velocity[touchdown]
    status = "SUCCESS" if 0.0 <= touchdown_velocity < safe_velocity else "CRASH"

    axes[0].plot(telemetry.time, telemetry.height, color="#1b9e77", linewidth=1.8)
    axes[0].axhline(0.0, color="black", linewidth=0.8)
    axes[0].set_ylabel("Altitude [m]")
    axes[0].set_title(f"Lunar lander touchdown — {status}")
    axes[0].grid(alpha=0.25)

    axes[1].plot(telemetry.time, telemetry.velocity, color="#7570b3", linewidth=1.8)
    axes[1].axhline(
        safe_velocity,
        color="#e7298a",
        linestyle="--",
        linewidth=1.0,
        label=f"safe limit ({safe_velocity:g} m/s)",
    )
    axes[1].set_ylabel("Downward velocity [m/s]")
    axes[1].legend(loc="best")
    axes[1].grid(alpha=0.25)

    _plot_engine_state(axes[2], telemetry)
    next_axis = 3
    if telemetry.is_2d and telemetry.x is not None and telemetry.vx is not None:
        axes[next_axis].plot(telemetry.time, telemetry.x, color="#66a61e", linewidth=1.8)
        axes[next_axis].axhline(0.0, color="black", linewidth=0.8)
        axes[next_axis].set_ylabel("Horizontal position [m]")
        axes[next_axis].grid(alpha=0.25)
        next_axis += 1
        axes[next_axis].plot(
            telemetry.time, telemetry.vx, color="#e6ab02", linewidth=1.8
        )
        axes[next_axis].set_ylabel("Horizontal velocity [m/s]")
        axes[next_axis].grid(alpha=0.25)

    for axis in axes:
        axis.axvline(touchdown_time, color="#666666", linestyle=":", linewidth=1.0)
    axes[-1].set_xlabel("Time [s]")
    axes[0].annotate(
        f"touchdown: {touchdown_time:.2f} s",
        xy=(touchdown_time, telemetry.height[touchdown]),
        xytext=(8, 8),
        textcoords="offset points",
        fontsize=9,
    )
    return figure


def main() -> int:
    args = parse_args()
    if args.safe_velocity <= 0:
        print("--safe-velocity must be greater than zero", file=sys.stderr)
        return 2
    if plt is None or matplotlib is None:
        print(
            "matplotlib is required; install dependencies with "
            "'python -m pip install -r requirements.txt'",
            file=sys.stderr,
        )
        return 2
    if args.show:
        backend = matplotlib.get_backend().lower()
        if not HAS_DISPLAY:
            print(
                "--show requires a graphical display. WSL1 is headless; "
                "use WSL2 with WSLg or omit --show to save the PNG.",
                file=sys.stderr,
            )
            return 2
        if "agg" in backend:
            print(
                f"--show cannot use the non-interactive matplotlib backend '{backend}'. "
                "Configure an interactive backend or omit --show.",
                file=sys.stderr,
            )
            return 2

    try:
        telemetry = load_telemetry(args.input)
        figure = create_figure(telemetry, args.safe_velocity)
        output = args.output or args.input.with_suffix(".png")
        output.parent.mkdir(parents=True, exist_ok=True)
        figure.savefig(output, dpi=160, bbox_inches="tight")
        if args.show:
            plt.show()
        plt.close(figure)
    except (OSError, ValueError) as error:
        print(f"plotting failed: {error}", file=sys.stderr)
        return 1

    print(f"Saved plot to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
